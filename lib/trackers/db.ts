/** Index domaine → entité, construit une fois au chargement du module. */
const DOMAIN_INDEX = new Map<string, TrackerEntity>();
for (const t of TRACKERS) {
  for (const d of t.domains) {
    DOMAIN_INDEX.set(d.toLowerCase(), t);
  }
}

const BY_SLUG = new Map(TRACKERS.map((t) => [t.slug, t]));

export function getTrackerBySlug(slug: string): TrackerEntity | undefined {
  return BY_SLUG.get(slug);
}

/**
 * Résout un nom d'hôte vers une entité connue.
 *
 * Le rapprochement se fait sur le suffixe : `www.google-analytics.com`
 * correspond à `google-analytics.com`. Les motifs contenant un chemin
 * (`facebook.com/tr`) sont testés contre l'URL complète par `matchUrl`.
 */
export function matchHostname(hostname: string): TrackerEntity | undefined {
  const host = hostname.toLowerCase().replace(/^www\./, "");
  const direct = DOMAIN_INDEX.get(host);
  if (direct) return direct;

  for (const [domain, entity] of DOMAIN_INDEX) {
    if (domain.includes("/")) continue;
    if (host === domain || host.endsWith("." + domain)) return entity;
  }
  return undefined;
}

/** Résout une URL complète, en tenant compte des motifs avec chemin. */
export function matchUrl(url: string): TrackerEntity | undefined {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return undefined;
  }

  const withoutScheme = (parsed.host + parsed.pathname).toLowerCase().replace(/^www\./, "");
  for (const [domain, entity] of DOMAIN_INDEX) {
    if (domain.includes("/") && withoutScheme.startsWith(domain)) return entity;
  }
  return matchHostname(parsed.hostname);
}

/** Recherche par marqueur textuel présent dans le HTML ou le JavaScript. */
export function matchMarkers(haystack: string): readonly TrackerEntity[] {
  const found: TrackerEntity[] = [];
  for (const t of TRACKERS) {
    if (!t.markers) continue;
    if (t.markers.some((m) => haystack.includes(m))) found.push(t);
  }
  return found;
}

